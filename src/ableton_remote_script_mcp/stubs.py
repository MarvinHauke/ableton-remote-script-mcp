"""Type stubs of a Live build for editor completion (plan 0001, after step 11; Decision 49 Q9).

`build-stubs <build>` writes one `.pyi` file per module of the build's Remote Scripts folder
(the framework generations, the libraries and the controller scripts) and a `Live` package, from
the API index. A Python language server (basedpyright, pyright, pylsp/jedi) reads them from its
stub path and completes names, signatures and docstrings while you write a script.

What a stub holds, all from the index (`observed`):
- a module's imports, as re-exports (`from m import X as X`), and its star imports;
- module constants and functions; classes with their bases as written, nested classes inside
  their class, methods with their parameters (literal defaults kept, others `...`), properties
  (with a setter when there is one), class attributes, and the instance attributes its methods
  assign (`self._x = …`, from the statement summaries);
- the members the index keeps as methods although they aren't (it holds the last `def` of a
  name): a property read from its `@<name>.setter`, controls and listener slots as attributes,
  and a `NamedTuple` (whose fields the index lacks) as a class that takes any field;
- the listener methods the framework makes from a class's `__events__` or
  `__subject_events__` (`add_<e>_listener` and so on), marked `documented`.

The `Live` package comes from the Push 3 helper's `live_model` (a model of Live's module, not
Live itself). With Structure Void's runtime pages imported, the members they list that the model
lacks are added, each marked `# documented`. `observed_only` leaves out both kinds of
`documented` member.

Nothing is typed beyond that: attributes, parameters and return values are `Any`, so a subclass
may set an attribute to anything, as the framework's own scripts do. The stubs are built from
Ableton's code, so like the index they stay on this machine and are never published.
"""

from __future__ import annotations

import ast
import keyword
import re
import shutil
from pathlib import Path

from .index_store import PUSH3_HELPER_ROOT, SCRIPTS_ROOT
from .names import event_methods

MARKER = ".ableton-remote-script-mcp-stubs"
LIVE_MODEL = "live_model.Live"
HEADER = ("# Generated by `ableton-remote-script-mcp build-stubs` from the API index of Live {build}.\n"
          "# Built from Ableton's code: keep it on this machine, never publish it.\n")


def _ok(name: str) -> bool:
    return name.isidentifier() and not keyword.iskeyword(name)


def _live_name(name: str) -> str | None:
    """`live_model.Live.Song.Song` -> `Live.Song.Song`; other `live_model` names -> None."""
    if name == LIVE_MODEL or name.startswith(LIVE_MODEL + "."):
        return "Live" + name[len(LIVE_MODEL):]
    if name == "live_model" or name.startswith("live_model."):
        return None
    return name


def _default(p: dict) -> str:
    value = p.get("default")
    if p.get("default_literal") and value is not None and len(value) <= 40:
        try:
            literal = ast.literal_eval(value)
        except (ValueError, SyntaxError):
            return "..."
        if literal is None or isinstance(literal, bool | int | float | str | bytes):
            return value
    return "..."


def _params(params: list[dict]) -> str:
    out: list[str] = []
    star = False
    for i, p in enumerate(params):
        name, kind = p["name"], p.get("kind", "positional_or_keyword")
        if not _ok(name):
            continue
        if kind == "var_positional":
            out.append(f"*{name}: Any")
            star = True
            continue
        if kind == "var_keyword":
            out.append(f"**{name}: Any")
            continue
        if kind == "keyword_only" and not star:
            out.append("*")
            star = True
        bare = i == 0 and name in ("self", "cls")  # the bound first parameter needs no type
        text = name + ("" if bare else ": Any") + (f" = {_default(p)}" if "default" in p else "")
        out.append(text)
        nxt = params[i + 1].get("kind") if i + 1 < len(params) else None
        if kind == "positional_only" and nxt != "positional_only":
            out.append("/")
    return ", ".join(out)


_SELF_ATTR = re.compile(r"^self\.([A-Za-z_]\w*)$")


def instance_attributes(members: dict) -> list[str]:
    """The `self.<name>` a class's methods assign (from the statement summaries), first seen first."""
    found: dict[str, None] = {}
    for m in members.values():
        for st in m.get("statements", []):
            for target in (st.get("store"), st.get("target")):
                for part in (target or "").split(","):
                    if match := _SELF_ATTR.match(part.strip()):
                        found.setdefault(match[1], None)
    return list(found)


def _doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return [f'{indent}"""{text}"""']


def _stored_function(m: dict) -> bool:
    """A function kept in a class attribute (`create_mappings_function = lambda *x: {}`): a
    "method" that takes no `self`. A subclass sets it to any function, so it is an attribute."""
    if m.get("kind") != "method":
        return False
    params = m.get("params") or []
    return not params or params[0].get("kind") in ("var_positional", "var_keyword", "keyword_only")


# Decorators that make a method into an object the class keeps under its name: a listener slot
# (`self._on_x.subject = …`) or a lazily computed attribute
_SLOT_DECORATORS = {"listens", "listens_group", "subject_slot", "subject_slot_group", "lazy_attribute"}
_PROPERTY_PARTS = {"setter", "getter", "deleter"}


def _decorator_head(decorator: str) -> str:
    return re.split(r"[(\[]", decorator, maxsplit=1)[0].strip()


def is_slot_or_control(name: str, m: dict) -> bool:
    """A "method" that is an object at runtime: a listener slot (`@listens(…)`) or a control whose
    handler was written under the control's own name (`@play_button.pressed` above
    `def play_button`; the control's decorator gives the control back). A handler under another
    name (`@jog.pressed` above `def _on_jog`) is the control too, but stays a method: nobody
    reads it, and it causes no error."""
    for d in m.get("decorators", []):
        head = _decorator_head(d)
        if head in _SLOT_DECORATORS:
            return True
        owner, _, part = head.partition(".")
        if owner == name and part and part not in _PROPERTY_PARTS:
            return True
    return False


def _method(name: str, m: dict, indent: str) -> list[str]:
    kind = m.get("kind")
    decorators = m.get("decorators", [])
    lines = []
    # A property whose getter isn't `@property` (v3's `listenable_property`): the index keeps the
    # last `def` of the name, the setter, so the getter is read from its `@<name>.setter`
    # (a `.deleter` or `.getter` last most likely follows a setter, so it keeps one)
    if any(f"{name}.{part}" in decorators for part in _PROPERTY_PARTS):
        m = {**m, "kind": "property", "params": [{"name": "self"}], "setter": True}
        kind = "property"
    is_property = kind == "property" or "listenable_property" in decorators
    if is_property:
        lines.append(f"{indent}@property")
    elif kind == "staticmethod":
        lines.append(f"{indent}@staticmethod")
    elif kind == "classmethod":
        lines.append(f"{indent}@classmethod")
    params = m.get("params") or ([] if kind == "staticmethod" else [{"name": "self"}])
    body = _doc(m.get("docstring"), indent + "    ")
    lines.append(f"{indent}def {name}({_params(params)}) -> Any:" + ("" if body else " ..."))
    lines += body
    if is_property and m.get("setter"):
        lines += [f"{indent}@{name}.setter", f"{indent}def {name}(self, value: Any) -> None: ..."]
    return lines


_NAMED_TUPLE = {"__init__": "def __init__(self, *a: Any, **k: Any) -> None: ...  # fields not in the index",
                "__getattr__": "def __getattr__(self, name: str) -> Any: ...",
                "__iter__": "def __iter__(self) -> Any: ...",
                "__getitem__": "def __getitem__(self, i: Any) -> Any: ..."}


class _Writer:
    def __init__(self, index: dict, documented: dict | None, observed_only: bool):
        self.index = index
        self.documented = None if observed_only else documented
        self.observed_only = observed_only
        self.by_module: dict[str, list[dict]] = {}
        for c in index["classes"].values():
            self.by_module.setdefault((c["root"], c["module"]), []).append(c)

    def _base(self, b: dict, live: bool) -> str | None:
        expr = b.get("expr", "")
        if live:  # a Live class: only bases inside Live itself
            resolved = _live_name(b.get("resolved") or "")
            return resolved if resolved and resolved.startswith("Live.") else None
        if not expr or expr == "object":
            return None
        return expr.split("[", 1)[0]

    def _class(self, c: dict, nested: dict[str, list[dict]], indent: str, live: bool) -> list[str]:
        bases = [b for b in (self._base(b, live) for b in c.get("bases", [])) if b]
        # A NamedTuple's fields are annotations, which the index doesn't hold: written as a plain
        # class that takes any arguments and has any attribute, not one with no fields
        named_tuple = any(b.get("resolved") == "typing.NamedTuple" for b in c.get("bases", []))
        if named_tuple:
            bases = [b for b in bases if b.rsplit(".", 1)[-1] != "NamedTuple"]
        head = f"{indent}class {c['name']}" + (f"({', '.join(bases)})" if bases else "") + ":"
        inner = indent + "    "
        body = _doc(c.get("docstring"), inner)
        children = nested.get(c["qualname"], [])
        child_names = {k["name"] for k in children}
        members = c.get("members", {})
        if named_tuple:
            body += [f"{inner}{line}" for name, line in _NAMED_TUPLE.items() if name not in members]
        for name, m in members.items():
            if not _ok(name) or name in child_names:
                continue
            if m.get("kind") == "attribute" or _stored_function(m) or is_slot_or_control(name, m):
                body.append(f"{inner}{name}: Any")
            else:
                body += _method(name, m, inner)
        for name in instance_attributes(members):
            if _ok(name) and name not in members and name not in child_names:
                body.append(f"{inner}{name}: Any")
        if not self.observed_only:
            for name in sorted(event_methods(members) - set(members)):
                body.append(f"{inner}def {name}(self, *a: Any, **k: Any) -> Any: ...  # documented: from __events__")
        page = (self.documented or {}).get("classes", {}).get(c.get("proxy_of") or "")
        if page:
            for name, m in page["members"].items():
                if _ok(name) and name not in members and name not in child_names:
                    if m.get("kind") == "property":
                        body.append(f"{inner}{name}: Any  # documented: Structure Void")
                    else:
                        body.append(f"{inner}def {name}(self, *a: Any, **k: Any) -> Any: ...  # documented: Structure Void")
        for child in sorted(children, key=lambda k: k.get("line") or 0):
            body += self._class(child, nested, inner, live)
        return [head] + (body or [f"{inner}..."])

    def module(self, m: dict, live: bool) -> str:
        lines = [HEADER.format(build=self.index["live_build"]), "from typing import Any", ""]
        lines += _doc(m.get("docstring"), "")
        classes = self.by_module.get((m["root"], m["name"]), [])
        defined = {c["name"] for c in classes if "." not in c["qualname"]} | set(m.get("members", {}))
        for star in m.get("star_imports", []):
            target = _live_name(star) if live else star
            if target:
                lines.append(f"from {target} import *")
        for alias, target in m.get("imports", {}).items():
            if not _ok(alias) or alias in defined or alias == "Any":
                continue
            target = _live_name(target) if live else target
            if not target:
                continue
            parent, _, name = target.rpartition(".")
            if not parent:
                lines.append(f"import {target} as {alias}")
            elif _ok(name):
                lines.append(f"from {parent} import {name} as {alias}")
        lines.append("")
        for name, member in m.get("members", {}).items():
            if not _ok(name):
                continue
            if member.get("kind") == "attribute":
                lines.append(f"{name}: Any")
            else:
                params = member.get("params", [])
                body = _doc(member.get("docstring"), "    ")
                lines.append(f"def {name}({_params(params)}) -> Any:" + ("" if body else " ..."))
                lines += body
        nested: dict[str, list[dict]] = {}
        for c in classes:
            if "." in c["qualname"]:
                nested.setdefault(c["qualname"].rsplit(".", 1)[0], []).append(c)
        for c in sorted((c for c in classes if "." not in c["qualname"]), key=lambda k: k.get("line") or 0):
            lines.append("")
            lines += self._class(c, nested, "", live)
        return "\n".join(lines) + "\n"


def _path(out: Path, name: str, package: bool) -> Path:
    parts = name.split(".")
    return out.joinpath(*parts, "__init__.pyi") if package else out.joinpath(*parts[:-1], parts[-1] + ".pyi")


def prepare_out(out: Path) -> None:
    """An empty folder for the stubs: a folder of earlier stubs (it has the marker) is replaced;
    any other folder that has files is refused."""
    if out.exists():
        if (out / MARKER).is_file():
            shutil.rmtree(out)
        elif any(out.iterdir()):
            raise FileExistsError(f"{out} has files that are not stubs of this tool; choose another --out")
    out.mkdir(parents=True, exist_ok=True)
    (out / MARKER).write_text("stubs written by ableton-remote-script-mcp build-stubs; this folder is replaced "
                              "when they are built again\n", encoding="utf-8")


def write_stubs(index: dict, out: Path, documented: dict | None = None, observed_only: bool = False) -> dict:
    """Write the stubs of one loaded index into `out` (see `prepare_out`)."""
    out = Path(out)
    prepare_out(out)
    writer = _Writer(index, documented, observed_only)
    files = 0
    written: set[Path] = set()
    for m in index["modules"].values():
        if m["root"] == SCRIPTS_ROOT:
            name, live = m["name"], False
        elif m["root"] == PUSH3_HELPER_ROOT and _live_name(m["name"]) not in (None, m["name"]):
            name, live = _live_name(m["name"]), True
        else:
            continue
        if not all(_ok(part) for part in name.split(".")):
            continue
        path = _path(out, name, m.get("package", False))
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(writer.module(m, live), encoding="utf-8")
        written.add(path)
        files += 1
    for folder in sorted({p.parent for p in written}):  # a package folder the index has no __init__ for
        while folder != out and out in folder.parents:
            init = folder / "__init__.pyi"
            if not init.exists():
                init.write_text(HEADER.format(build=index["live_build"]), encoding="utf-8")
                files += 1
            folder = folder.parent
    return {"status": "ok", "live_build": index["live_build"], "out": str(out), "files": files,
            "documented": not observed_only, "structure_void": documented is not None and not observed_only}
