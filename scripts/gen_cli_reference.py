"""Generate the CLI reference page (docs/reference/cli.md) from the command's argument parser.

    uv run python scripts/gen_cli_reference.py            # write the page
    uv run python scripts/gen_cli_reference.py --check    # exit 1 when the committed page is stale

The page is never edited by hand: change a command's help text in `cli.py` and run this again.
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "docs" / "reference" / "cli.md"
PROG = "ableton-remote-script-mcp"

HEADER = """\
<!-- Generated by scripts/gen_cli_reference.py from the argument parser. Do not edit by hand. -->

# CLI reference

Every command is run as `uv run ableton-remote-script-mcp <command>` from a clone of the
repository. The global option goes before the command:
`uv run ableton-remote-script-mcp --index-dir <folder> lookup class Component`.
"""


def _subcommands(parser: argparse.ArgumentParser) -> list[tuple[str, str, argparse.ArgumentParser]]:
    """(name, help, parser) for each subcommand, in the order they were added."""
    out = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {a.dest: a.help or "" for a in action._choices_actions}
            out += [(name, helps.get(name, ""), sub) for name, sub in action.choices.items()]
    return out


def _arg_name(a: argparse.Action) -> str:
    if a.option_strings:
        name = ", ".join(a.option_strings)
        return name if a.nargs == 0 else f"{name} {a.metavar or a.dest.upper()}"
    name = a.metavar or a.dest
    return f"{name} …" if a.nargs == "+" else name


def _arguments(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in parser._actions
            if not isinstance(a, (argparse._HelpAction, argparse._SubParsersAction))]


def _sentence(text: str) -> str:
    text = text.strip()
    if not text:
        return ""
    text = text[0].upper() + text[1:]
    return text if text.endswith(".") else text + "."


def _usage(path: list[str], parser: argparse.ArgumentParser) -> str:
    options = [f"[{_arg_name(a)}]" for a in _arguments(parser) if a.option_strings]
    positionals = [_arg_name(a) for a in _arguments(parser) if not a.option_strings]
    return " ".join([PROG, *path, *options, *positionals])


def _option_rows(parser: argparse.ArgumentParser) -> list[str]:
    rows = []
    for a in _arguments(parser):
        text = _sentence((a.help or "") % {"default": a.default})
        if a.choices and not isinstance(a.choices, dict):
            text += f" One of: {', '.join(f'`{c}`' for c in a.choices)}."
        text = text.replace("|", r"\|")
        rows.append(f"| `{_arg_name(a)}` | {text.strip()} |")
    return rows


def _section(path: list[str], help_text: str, parser: argparse.ArgumentParser, level: int) -> list[str]:
    subs = _subcommands(parser)
    lines = [f"{'#' * level} `{' '.join(path)}`", ""]
    if help_text:
        lines += [_sentence(help_text), ""]
    if not subs:
        lines += ["```text", _usage(path, parser), "```", ""]
        rows = _option_rows(parser)
        if rows:
            lines += ["| Argument | What it does |", "| --- | --- |", *rows, ""]
    for name, sub_help, sub in subs:
        lines += _section([*path, name], sub_help, sub, level + 1)
    return lines


def render() -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from ableton_remote_script_mcp.cli import make_parser

    parser = make_parser()
    lines = [HEADER, "## Global options", "", "| Option | What it does |", "| --- | --- |"]
    lines += _option_rows(parser) + [""]
    for name, help_text, sub in _subcommands(parser):
        lines += _section([name], help_text, sub, 2)
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare with the page instead of writing it")
    ap.add_argument("--page", type=Path, default=PAGE, help="the page to write or check")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = args.page.read_text() if args.page.is_file() else ""
        if current == text:
            return 0
        sys.stdout.writelines(difflib.unified_diff(
            current.splitlines(True), text.splitlines(True), str(args.page), "generated"))
        print(f"\n{args.page} is stale: run `uv run python scripts/gen_cli_reference.py`", file=sys.stderr)
        return 1
    args.page.parent.mkdir(parents=True, exist_ok=True)
    args.page.write_text(text)
    print(f"wrote {args.page}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
